import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { iconPdf } from './lib/pdf.mjs';
import { shapeToPath, tokenize, toAbsolute } from './lib/svg-path.mjs';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = resolve(SCRIPT_DIR, '..');
const DEFAULT_MANIFEST = join(SCRIPT_DIR, 'icons.json');

const CATALOG = 'ios/Baupilot/Resources/Icons.xcassets';
const SWIFT_PATH = 'ios/Baupilot/DesignSystem/Icons.swift';
const KOTLIN_PATH = 'android/app/src/main/java/de/baupilot/designsystem/Icons.kt';
const DRAWABLES = 'android/app/src/main/res/drawable';
const HEADER = '// GENERATED by scripts/gen-icons from scripts/icons.json — do not edit.';

const NAME_RE = /^ic_[a-z0-9_]+$/;
const CHILD_RE = /<(path|circle|rect|line|polyline|polygon)\b([^<>]*?)\s*\/>/y;
const ATTR_RE = /([a-zA-Z][\w-]*)="([^"]*)"/g;
const CAPS = ['butt', 'round', 'square'];
const JOINS = ['miter', 'round', 'bevel'];

export class IconError extends Error {
  constructor(code, entry, message) {
    super(`gen-icons: ${code}: ${entry}: ${message}`);
    this.name = 'IconError';
    this.code = code;
    this.entry = entry;
  }
}

/** The children of a manifest `svg` string as `{ tag, attrs }`; anything else is a `bad-svg`. */
function parseChildren(svg, entry) {
  if (typeof svg !== 'string') throw new IconError('bad-svg', entry, 'svg must be a string');
  const children = [];
  let at = 0;
  for (;;) {
    while (/\s/.test(svg[at] ?? '')) at += 1;
    if (at >= svg.length) break;
    CHILD_RE.lastIndex = at;
    const m = CHILD_RE.exec(svg);
    if (!m) throw new IconError('bad-svg', entry, `unsupported markup at ${at}: ${svg.slice(at, at + 24)}`);
    children.push({ tag: m[1], attrs: Object.fromEntries([...m[2].matchAll(ATTR_RE)].map((a) => [a[1], a[2]])) });
    at += m[0].length;
  }
  if (children.length === 0) throw new IconError('bad-svg', entry, 'svg has no children');
  return children;
}

/** Path data (SVG syntax) of one child; the PDF commands are derived from the same string. */
function childPaths(svg, entry) {
  return parseChildren(svg, entry).map((child) => {
    let d;
    try {
      d = shapeToPath(child);
      if (tokenize(d).length === 0) throw new Error('empty path data');
    } catch (error) {
      throw new IconError('bad-svg', entry, error.message);
    }
    return d;
  });
}

const withDefaults = (icon) => ({
  fill: false,
  lineCap: 'round',
  lineJoin: 'round',
  ...icon,
});

export function validateManifest(manifest) {
  const seen = new Set();
  for (const raw of manifest.icons ?? []) {
    const name = raw?.name;
    if (typeof name !== 'string' || !NAME_RE.test(name)) throw new IconError('bad-name', String(name), 'name must match ^ic_[a-z0-9_]+$');
    if (seen.has(name)) throw new IconError('duplicate-name', name, 'name is used twice');
    seen.add(name);
    const icon = withDefaults(raw);
    childPaths(icon.svg, name);
    if (!icon.fill && !(typeof icon.stroke === 'number' && icon.stroke > 0)) {
      throw new IconError('bad-stroke', name, 'a stroke icon needs a positive stroke width');
    }
    if (!CAPS.includes(icon.lineCap)) throw new IconError('bad-stroke', name, `unknown lineCap ${icon.lineCap}`);
    if (!JOINS.includes(icon.lineJoin)) throw new IconError('bad-stroke', name, `unknown lineJoin ${icon.lineJoin}`);
  }
  for (const alias of manifest.aliases ?? []) {
    if (!seen.has(alias.asset)) throw new IconError('bad-alias', String(alias.asset), 'alias target is not an icon');
    parseChildren(alias.svg, alias.asset);
  }
}

const camel = (name, upperFirst) =>
  name
    .replace(/^ic_/, '')
    .split('_')
    .map((part, i) => (i === 0 && !upperFirst ? part : part.charAt(0).toUpperCase() + part.slice(1)))
    .join('');

const num = (n) => String(n);

function vectorDrawable(icon) {
  const paths = childPaths(icon.svg, icon.name).map((d) => {
    const attrs = [`android:pathData="${d}"`];
    if (icon.fill) {
      attrs.push('android:fillColor="@android:color/black"');
    } else {
      attrs.push(
        'android:strokeColor="@android:color/black"',
        `android:strokeWidth="${num(icon.stroke)}"`,
        `android:strokeLineCap="${icon.lineCap}"`,
        `android:strokeLineJoin="${icon.lineJoin}"`,
      );
    }
    return `    <path\n${attrs.map((a) => `        ${a}`).join('\n')} />`;
  });
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${HEADER.slice(3)} -->`,
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    '    android:width="24dp"',
    '    android:height="24dp"',
    '    android:viewportWidth="24"',
    '    android:viewportHeight="24">',
    ...paths,
    '</vector>',
    '',
  ].join('\n');
}

function pdf(icon) {
  const commands = childPaths(icon.svg, icon.name).flatMap((d) => toAbsolute(tokenize(d)));
  return iconPdf({ commands, stroke: icon.stroke, fill: icon.fill, lineCap: icon.lineCap, lineJoin: icon.lineJoin });
}

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;

function swiftSource(icons) {
  return [
    HEADER,
    '',
    '/// Every generated icon asset. Draw it as a template image and tint it at runtime.',
    'public enum BaupilotIcon: String, CaseIterable {',
    ...icons.map((i) => `    case ${camel(i.name, false)} = "${i.name}"`),
    '}',
    '',
  ].join('\n');
}

function kotlinSource(icons) {
  return [
    HEADER,
    '',
    'package de.baupilot.designsystem',
    '',
    'import androidx.annotation.DrawableRes',
    'import de.baupilot.R',
    '',
    '/** Every generated icon drawable. Draw it with a tint; the vector itself is black. */',
    'enum class BaupilotIcon(@DrawableRes val res: Int) {',
    ...icons.map((i) => `    ${camel(i.name, true)}(R.drawable.${i.name}),`),
    '}',
    '',
  ].join('\n');
}

/** Relative path -> Buffer for every generated file. */
export function buildOutputs(manifest) {
  validateManifest(manifest);
  const icons = manifest.icons.map(withDefaults);
  const out = new Map();
  out.set(`${CATALOG}/Contents.json`, Buffer.from(json({ info: { author: 'xcode', version: 1 } })));
  for (const icon of icons) {
    const set = `${CATALOG}/${icon.name}.imageset`;
    out.set(
      `${set}/Contents.json`,
      Buffer.from(
        json({
          images: [{ filename: `${icon.name}.pdf`, idiom: 'universal' }],
          info: { author: 'xcode', version: 1 },
          properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' },
        }),
      ),
    );
    out.set(`${set}/${icon.name}.pdf`, pdf(icon));
    out.set(`${DRAWABLES}/${icon.name}.xml`, Buffer.from(vectorDrawable(icon)));
  }
  out.set(SWIFT_PATH, Buffer.from(swiftSource(icons)));
  out.set(KOTLIN_PATH, Buffer.from(kotlinSource(icons)));
  return out;
}

/** Existing `ic_*` outputs the manifest no longer names (relative paths). */
function staleOutputs(root, outputs) {
  const stale = [];
  const scan = (dir, pattern) => {
    const abs = join(root, dir);
    if (!existsSync(abs)) return;
    for (const entry of readdirSync(abs).sort()) {
      const rel = `${dir}/${entry}`;
      if (pattern.test(entry) && !outputs.has(rel) && ![...outputs.keys()].some((k) => k.startsWith(`${rel}/`))) stale.push(rel);
    }
  };
  scan(CATALOG, /^ic_[a-z0-9_]+\.imageset$/);
  scan(DRAWABLES, /^ic_[a-z0-9_]+\.xml$/);
  return stale;
}

export function run({ root = DEFAULT_ROOT, manifestPath, manifest, check = false } = {}) {
  const source = manifest ?? JSON.parse(readFileSync(manifestPath ? resolve(manifestPath) : DEFAULT_MANIFEST, 'utf8'));
  let outputs;
  try {
    outputs = buildOutputs(source);
  } catch (error) {
    if (error instanceof IconError) return { code: 2, written: [], stale: [], error };
    throw error;
  }
  const stale = staleOutputs(root, outputs);
  if (check) {
    const drift = [...outputs]
      .filter(([rel, bytes]) => !existsSync(join(root, rel)) || !readFileSync(join(root, rel)).equals(bytes))
      .map(([rel]) => rel);
    const all = [...drift, ...stale];
    return { code: all.length > 0 ? 1 : 0, written: [], stale: all };
  }
  for (const rel of stale) rmSync(join(root, rel), { recursive: true, force: true });
  for (const [rel, bytes] of outputs) {
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    writeFileSync(join(root, rel), bytes);
  }
  return { code: 0, written: [...outputs.keys()], stale: [] };
}

function main() {
  const { values } = parseArgs({
    options: {
      check: { type: 'boolean', default: false },
      root: { type: 'string' },
      manifest: { type: 'string' },
    },
  });
  const root = values.root ? resolve(values.root) : DEFAULT_ROOT;
  const result = run({ root, manifestPath: values.manifest, check: values.check });
  if (result.error) {
    console.error(result.error.message);
  } else if (result.stale.length > 0) {
    console.error('gen-icons: generated files are out of date:');
    for (const rel of result.stale) console.error(`  ${relative(root, join(root, rel))}`);
  } else if (!values.check) {
    console.log(`gen-icons: wrote ${result.written.length} files`);
  }
  process.exitCode = result.code;
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  try {
    main();
  } catch (error) {
    console.error(`gen-icons: ${error.message}`);
    process.exitCode = 2;
  }
}
