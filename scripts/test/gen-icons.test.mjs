// ---- manifest validation ----

const icon = (extra = {}) => ({ name: 'ic_a', svg: '<path d="M5 12l5 5 9-10"/>', stroke: 2, fill: false, lineJoin: 'round', lineCap: 'round', sources: [], ...extra });
const withIcons = (...icons) => ({ icons, aliases: [], nonIcons: [] });

function refuse(bad, code, entry) {
  assert.throws(
    () => validateManifest(bad),
    (e) => e instanceof IconError && e.code === code && e.entry === entry,
  );
  const root = tempRoot();
  try {
    const file = join(root, 'icons.json');
    writeFileSync(file, JSON.stringify(bad));
    const result = cli(['--check', '--root', root, '--manifest', file]);
    assert.equal(result.status, 2, result.stdout + result.stderr);
    assert.match(result.stderr, new RegExp(`${code}.*${entry}`));
    assert.equal(existsSync(join(root, 'android')), false);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

test('validation: bad-name', () => {
  refuse(withIcons(icon({ name: 'Check' })), 'bad-name', 'Check');
  refuse(withIcons(icon({ name: 'check' })), 'bad-name', 'check');
});

test('validation: duplicate-name', () => {
  refuse(withIcons(icon(), icon({ svg: '<path d="M1 1l2 2"/>' })), 'duplicate-name', 'ic_a');
});

test('validation: bad-svg', () => {
  refuse(withIcons(icon({ svg: '<g><path d="M1 1l2 2"/></g>' })), 'bad-svg', 'ic_a');
  refuse(withIcons(icon({ svg: '' })), 'bad-svg', 'ic_a');
  refuse(withIcons(icon({ svg: '<path d="L1 1"/>' })), 'bad-svg', 'ic_a');
  refuse(withIcons(icon({ svg: '<path d="M1 1l2 2"/> stray' })), 'bad-svg', 'ic_a');
});

test('validation accepts every allowed child element', () => {
  const svg = [
    '<path d="M1 1l2 2"/>',
    '<circle cx="12" cy="12" r="3"/>',
    '<rect x="3" y="5" width="18" height="14" rx="2"/>',
    '<line x1="1" y1="1" x2="5" y2="5"/>',
    '<polyline points="1 1 5 5 9 1"/>',
    '<polygon points="1 1 5 5 9 1"/>',
  ].join('');
  assert.doesNotThrow(() => validateManifest(withIcons(icon({ svg }))));
  const root = tempRoot();
  try {
    assert.equal(run({ root, manifest: withIcons(icon({ svg })) }).code, 0);
    const xml = readFileSync(join(root, DRAWABLES, 'ic_a.xml'), 'utf8');
    assert.equal(xml.match(/<path/g).length, 6);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
