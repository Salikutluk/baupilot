import { test } from 'node:test';
import assert from 'node:assert/strict';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseScreens } from '../lib/screens.mjs';
import { generateKotlin, generateSwift, TokenError, validateTokens } from '../lib/tokens.mjs';
import { run } from '../gen-tokens.mjs';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const real = JSON.parse(readFileSync(join(REPO, 'design', 'tokens.json'), 'utf8'));
const screenNames = parseScreens(readFileSync(join(REPO, 'design', 'screens.md'), 'utf8')).map((s) => s.name);

const SWIFT = 'ios/Baupilot/DesignSystem/Tokens.swift';
const KOTLIN = 'android/app/src/main/java/de/baupilot/designsystem/Tokens.kt';

const clone = (v) => structuredClone(v);

function tempRoot(tokens = real) {
  const root = mkdtempSync(join(tmpdir(), 'gen-tokens-'));
  mkdirSync(join(root, 'design'));
  cpSync(join(REPO, 'design', 'screens.md'), join(root, 'design', 'screens.md'));
  writeFileSync(join(root, 'design', 'tokens.json'), JSON.stringify(tokens));
  return root;
}

function refuse(mutate, code, path) {
  const json = clone(real);
  mutate(json);
  assert.throws(
    () => validateTokens(json, screenNames),
    (e) => e instanceof TokenError && e.code === code && e.path === path,
  );
  const root = tempRoot(json);
  try {
    const result = run({ root });
    assert.equal(result.code, 2);
    assert.equal(result.error.code, code);
    assert.equal(result.error.path, path);
    assert.deepEqual(result.written, []);
    assert.equal(existsSync(join(root, SWIFT)), false);
    assert.equal(existsSync(join(root, KOTLIN)), false);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

test('real tokens validate and generation is byte-identical', () => {
  validateTokens(real, screenNames);
  assert.equal(generateSwift(real), generateSwift(real));
  assert.equal(generateKotlin(real), generateKotlin(real));
  for (const out of [generateSwift(real), generateKotlin(real)]) {
    assert.ok(out.startsWith('// GENERATED by scripts/gen-tokens from design/tokens.json — do not edit.\n'));
    assert.ok(out.endsWith('\n') && !out.endsWith('\n\n'));
    assert.ok(!out.includes('\r'));
  }
});

test('run writes both files, a second run with check is clean', () => {
  const root = tempRoot();
  try {
    const first = run({ root });
    assert.equal(first.code, 0);
    assert.deepEqual(first.written, [join(root, SWIFT), join(root, KOTLIN)]);
    const second = run({ root, check: true });
    assert.equal(second.code, 0);
    assert.deepEqual(second.stale, []);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('check reports a hand-edited file as stale, a missing file too', () => {
  const root = tempRoot();
  try {
    run({ root });
    writeFileSync(join(root, SWIFT), `${readFileSync(join(root, SWIFT), 'utf8')}// edited\n`);
    const drift = run({ root, check: true });
    assert.equal(drift.code, 1);
    assert.deepEqual(drift.stale, [join(root, SWIFT)]);
    rmSync(join(root, KOTLIN));
    assert.deepEqual(run({ root, check: true }).stale, [join(root, SWIFT), join(root, KOTLIN)]);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('Swift output: literals, alpha last, keyword backticks', () => {
  const swift = generateSwift(real);
  assert.ok(swift.includes('static let accent = ColorToken(light: 0xC2410CFF, dark: 0xFB923CFF)'));
  assert.ok(swift.includes('0xFFFFFFF2'));
  assert.ok(swift.includes('static let `open` = ColorToken('));
  assert.ok(swift.includes('static let cardHero: CGFloat = 18'));
});

test('Kotlin output: alpha first for a synthetic #FFFFFFF2', () => {
  const json = clone(real);
  json.android.colors.core.bg = { light: '#FFFFFFF2', dark: '#000000' };
  assert.ok(generateKotlin(json).includes('Color(0xF2FFFFFF)'));
  assert.ok(generateKotlin(json).includes('Color(0xFF000000)'));
});

test('variants: Swift dynamic-member struct, Kotlin object extending ColorToken', () => {
  const swift = generateSwift(real);
  assert.ok(swift.includes('@dynamicMemberLookup\npublic struct TrackVariants: Sendable {'));
  assert.ok(swift.includes('public let abnPruefung: ColorToken'));
  assert.ok(swift.includes('static let track = TrackVariants()'));
  const kotlin = generateKotlin(real);
  assert.ok(kotlin.includes('object track : ColorToken('));
  assert.ok(kotlin.includes('val abnElemente = ColorToken('));
});

test('layout: sizes, padding arrays and pairs', () => {
  const swift = generateSwift(real);
  const kotlin = generateKotlin(real);
  assert.ok(swift.includes('CGSize(width: 390, height: 844)'));
  assert.ok(kotlin.includes('DpSize(390.dp, 844.dp)'));
  assert.ok(swift.includes('EdgeInsets(top: 12, leading: 20, bottom: 34, trailing: 20)'));
  assert.ok(kotlin.includes('PaddingValues(start = 16.dp, top = 12.dp, end = 16.dp, bottom = 24.dp)'));
  assert.ok(kotlin.includes('val navPill = DpSize(56.dp, 32.dp)'));
});

test('refuses #FFF', () => refuse((j) => { j.ios.colors.core.accent.light = '#FFF'; }, 'invalid-hex', 'ios.colors.core.accent.light'));

test('refuses an invalid hex in perScreen with the documented message', () => {
  const json = clone(real);
  json.ios.colors.perScreen.Login.border.dark = 'blue';
  assert.throws(
    () => validateTokens(json, screenNames),
    (e) =>
      e.code === 'invalid-hex' &&
      e.path === 'ios.colors.perScreen.Login.border.dark' &&
      e.message === 'gen-tokens: invalid color at ios.colors.perScreen.Login.border.dark: "blue" (expected #RRGGBB or #RRGGBBAA)',
  );
});

test('refuses an incomplete pair', () =>
  refuse((j) => { delete j.android.colors.core.bg.dark; }, 'incomplete-pair', 'android.colors.core.bg.dark'));

test('refuses a perScreen token missing from core', () =>
  refuse((j) => { j.ios.colors.perScreen.Login.nope = { light: '#000000', dark: '#FFFFFF' }; }, 'unknown-token', 'ios.colors.perScreen.Login.nope'));

test('refuses a perScreen screen missing from screens.md', () =>
  refuse((j) => { j.ios.colors.perScreen.Nope = { border: { light: '#000000', dark: '#FFFFFF' } }; }, 'unknown-screen', 'ios.colors.perScreen.Nope'));

test('refuses keys colliding after camelCasing', () =>
  refuse((j) => { j.ios.radius.cardHero = 1; }, 'name-collision', 'ios.radius.cardHero'));

test('refuses a screen key that equals a reserved variant member', () =>
  refuse((j) => { j.ios.colors.perScreen.Core = { border: { light: '#000000', dark: '#FFFFFF' } }; }, 'name-collision', 'ios.colors.perScreen.Core'));

test('refuses an unsupported layout value', () =>
  refuse((j) => { j.android.layout.gutter = '12px'; }, 'unsupported-layout', 'android.layout.gutter'));
