import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseScreens } from '../lib/screens.mjs';
import { generateKotlin, generateSwift, mergeSupplement, TokenError, validateSupplement, validateTokens } from '../lib/tokens.mjs';
import { run } from '../gen-tokens.mjs';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const real = JSON.parse(readFileSync(join(REPO, 'design', 'tokens.json'), 'utf8'));
const screenNames = parseScreens(readFileSync(join(REPO, 'design', 'screens.md'), 'utf8')).map((s) => s.name);

const SWIFT = 'ios/Baupilot/DesignSystem/Tokens.swift';
const KOTLIN = 'android/app/src/main/java/de/baupilot/designsystem/Tokens.kt';

const clone = (v) => structuredClone(v);

const SUPPLEMENT_FILE = join(REPO, 'scripts', 'tokens-supplement.json');
const realSupplement = JSON.parse(readFileSync(SUPPLEMENT_FILE, 'utf8'));
const SUPPLEMENT_HEADER = '// GENERATED by scripts/gen-tokens from design/tokens.json + scripts/tokens-supplement.json — do not edit.\n';
const DESIGN_HEADER = '// GENERATED by scripts/gen-tokens from design/tokens.json — do not edit.\n';

const synthetic = () => ({
  ios: { colors: { zeta: { light: '#112233', dark: '#445566', source: 'X.dc.html:1' }, alpha: { light: '#000000', dark: '#FFFFFF80', source: 'X.dc.html:2' } } },
  android: { colors: { fabEdge: { light: '#0000002E', dark: '#0000002E', source: 'Y.dc.html:3' } } },
});

function writeSupplement(root, supplement, name = 'scripts/tokens-supplement.json') {
  mkdirSync(dirname(join(root, name)), { recursive: true });
  writeFileSync(join(root, name), JSON.stringify(supplement));
}

function refuseSupplement(mutate, code, path) {
  const supplement = synthetic();
  mutate(supplement);
  assert.throws(
    () => validateSupplement(supplement, real),
    (e) => e instanceof TokenError && e.code === code && e.path === path,
  );
  const root = tempRoot();
  try {
    writeSupplement(root, supplement);
    const result = run({ root });
    assert.equal(result.code, 2);
    assert.equal(result.error.code, code);
    assert.equal(result.error.path, path);
    assert.equal(existsSync(join(root, SWIFT)), false);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

function tempRoot(tokens = real) {
  const root = mkdtempSync(join(tmpdir(), 'gen-tokens-'));
  mkdirSync(join(root, 'design'));
  cpSync(join(REPO, 'design', 'screens.md'), join(root, 'design', 'screens.md'));
  writeFileSync(join(root, 'design', 'tokens.json'), JSON.stringify(tokens));
  return root;
}

function refuse(mutate, code, path) {
  const json = clone(real);
  mutate(json);
  assert.throws(
    () => validateTokens(json, screenNames),
    (e) => e instanceof TokenError && e.code === code && e.path === path,
  );
  const root = tempRoot(json);
  try {
    const result = run({ root });
    assert.equal(result.code, 2);
    assert.equal(result.error.code, code);
    assert.equal(result.error.path, path);
    assert.deepEqual(result.written, []);
    assert.equal(existsSync(join(root, SWIFT)), false);
    assert.equal(existsSync(join(root, KOTLIN)), false);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

test('real tokens validate and generation is byte-identical', () => {
  validateTokens(real, screenNames);
  validateSupplement(realSupplement, real);
  const merged = mergeSupplement(real, realSupplement);
  const swift = generateSwift(merged, { supplement: true });
  const kotlin = generateKotlin(merged, { supplement: true });
  assert.equal(swift, generateSwift(merged, { supplement: true }));
  assert.equal(kotlin, generateKotlin(merged, { supplement: true }));
  assert.equal(swift, readFileSync(join(REPO, SWIFT), 'utf8'));
  assert.equal(kotlin, readFileSync(join(REPO, KOTLIN), 'utf8'));
  for (const out of [swift, kotlin]) {
    assert.ok(out.startsWith(SUPPLEMENT_HEADER));
    assert.ok(out.endsWith('\n') && !out.endsWith('\n\n'));
    assert.ok(!out.includes('\r'));
  }
});

test('supplement tokens are emitted into Tokens.swift and Tokens.kt', () => {
  const merged = mergeSupplement(real, synthetic());
  const swift = generateSwift(merged, { supplement: true });
  const kotlin = generateKotlin(merged, { supplement: true });
  assert.ok(swift.includes('static let zeta = ColorToken(light: 0x112233FF, dark: 0x445566FF)'));
  assert.ok(swift.includes('static let alpha = ColorToken(light: 0x000000FF, dark: 0xFFFFFF80)'));
  assert.ok(kotlin.includes('val fabEdge = ColorToken(Color(0x2E000000), Color(0x2E000000))'));
  assert.ok(!swift.includes('X.dc.html'));
  // after the design core tokens, sorted by name
  const lastDesign = Object.keys(real.ios.colors.core).at(-1);
  const idx = (name) => swift.indexOf(`static let ${name} =`);
  assert.ok(idx(lastDesign) < idx('alpha'));
  assert.ok(idx('alpha') < idx('zeta'));
});

test('supplement name colliding with design core fails with name-collision', () =>
  refuseSupplement((s) => { s.ios.colors.accent = { light: '#000000', dark: '#000000', source: 'X.dc.html:9' }; }, 'name-collision', 'supplement.ios.colors.accent'));

test('supplement name colliding with another supplement entry fails with name-collision', () =>
  refuseSupplement((s) => { s.ios.colors['fab-edge'] = { light: '#000000', dark: '#000000', source: 'X.dc.html:9' }; s.ios.colors.fabEdge = { light: '#000000', dark: '#000000', source: 'X.dc.html:9' }; }, 'name-collision', 'supplement.ios.colors.fabEdge'));

test('supplement entry without source fails with missing-source', () =>
  refuseSupplement((s) => { s.ios.colors.zeta.source = ''; }, 'missing-source', 'supplement.ios.colors.zeta'));

test('supplement invalid hex fails with invalid-hex at supplement.<platform>.colors.<name>.light', () =>
  refuseSupplement((s) => { s.android.colors.fabEdge.light = '#FFF'; }, 'invalid-hex', 'supplement.android.colors.fabEdge.light'));

test('supplement entry without dark fails with incomplete-pair at ….<name>.dark', () =>
  refuseSupplement((s) => { delete s.ios.colors.zeta.dark; }, 'incomplete-pair', 'supplement.ios.colors.zeta.dark'));

test('mergeSupplement does not mutate its inputs', () => {
  const tokens = clone(real);
  const supplement = synthetic();
  const tokensBefore = clone(tokens);
  const supplementBefore = clone(supplement);
  const merged = mergeSupplement(tokens, supplement);
  assert.deepEqual(tokens, tokensBefore);
  assert.deepEqual(supplement, supplementBefore);
  assert.notEqual(merged, tokens);
  assert.ok('zeta' in merged.ios.colors.core);
  assert.ok(!('zeta' in tokens.ios.colors.core));
});

test('explicit --supplement path that does not exist exits 2', () => {
  const root = tempRoot();
  try {
    const missing = join(root, 'nope.json');
    assert.throws(
      () => run({ root, supplementPath: missing }),
      (e) => e instanceof TokenError && e.code === 'supplement-missing' && e.path === missing,
    );
    const cli = spawnSync(process.execPath, [join(REPO, 'scripts', 'gen-tokens.mjs'), '--root', root, '--supplement', missing], { encoding: 'utf8' });
    assert.equal(cli.status, 2);
    assert.match(cli.stderr, /nope\.json/);
    assert.equal(existsSync(join(root, SWIFT)), false);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('missing default supplement file generates design-only tokens with the unchanged header', () => {
  const root = tempRoot();
  try {
    const result = run({ root });
    assert.equal(result.code, 0);
    for (const file of [SWIFT, KOTLIN]) {
      const out = readFileSync(join(root, file), 'utf8');
      assert.ok(out.startsWith(DESIGN_HEADER));
      assert.ok(!out.includes('tokens-supplement'));
    }
    assert.ok(!readFileSync(join(root, SWIFT), 'utf8').includes('static let knob'));
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('run with a supplement writes both files; a second run with --check is clean', () => {
  const root = tempRoot();
  try {
    writeSupplement(root, synthetic());
    const first = run({ root });
    assert.equal(first.code, 0);
    assert.deepEqual(first.written, [join(root, SWIFT), join(root, KOTLIN)]);
    assert.ok(readFileSync(join(root, SWIFT), 'utf8').startsWith(SUPPLEMENT_HEADER));
    assert.ok(readFileSync(join(root, KOTLIN), 'utf8').includes('val fabEdge ='));
    const second = run({ root, check: true });
    assert.equal(second.code, 0);
    assert.deepEqual(second.stale, []);
    writeSupplement(root, synthetic(), 'custom/supp.json');
    assert.equal(run({ root, check: true, supplementPath: join(root, 'custom', 'supp.json') }).code, 0);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('run writes both files, a second run with check is clean', () => {
  const root = tempRoot();
  try {
    const first = run({ root });
    assert.equal(first.code, 0);
    assert.deepEqual(first.written, [join(root, SWIFT), join(root, KOTLIN)]);
    const second = run({ root, check: true });
    assert.equal(second.code, 0);
    assert.deepEqual(second.stale, []);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('check reports a hand-edited file as stale, a missing file too', () => {
  const root = tempRoot();
  try {
    run({ root });
    writeFileSync(join(root, SWIFT), `${readFileSync(join(root, SWIFT), 'utf8')}// edited\n`);
    const drift = run({ root, check: true });
    assert.equal(drift.code, 1);
    assert.deepEqual(drift.stale, [join(root, SWIFT)]);
    rmSync(join(root, KOTLIN));
    assert.deepEqual(run({ root, check: true }).stale, [join(root, SWIFT), join(root, KOTLIN)]);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

